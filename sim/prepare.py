#!/usr/bin/env python3
"""Turn exported animations into a simulator input (a Lua data file).
   python3 sim/prepare.py ANIMS.json OUT.lua ID[:LOOPS] [ID[:LOOPS] ...] [--blend 0.2] [--hold 0.6]
Plays the listed animations one after another (each looped LOOPS times, default 2), cross-fading
--blend seconds between them, then --hold seconds standing in the last pose (to watch it settle).
The game's animations run in place (the engine moves the character), so world motion is rebuilt:
while a foot is planted (the lower foot), the body moves so that the foot stays put. That gives the
skirt the right inertia when walking/running and stopping."""
import json, math, sys

args = sys.argv[1:]
def opt(name, default):
    if name in args:
        i = args.index(name); v = float(args[i + 1]); del args[i:i + 2]; return v
    return default
BLEND, HOLD = opt('--blend', 0.2), opt('--hold', 0.6)
SPEED = opt('--speed', 1.0)   # scale the rebuilt world motion (the game moves the body faster than the planted-foot estimate)
src, out, specs = args[0], args[1], args[2:]
D = json.load(open(src))
by_id = {a['id']: a for a in D['anims']}
bones = D['bones']

def nlerp(a, b, t):
    if sum(x * y for x, y in zip(a, b)) < 0: b = [-x for x in b]
    q = [x + (y - x) * t for x, y in zip(a, b)]
    n = math.sqrt(sum(x * x for x in q)) or 1
    return [x / n for x in q]
def mix(fa, fb, t):
    return {b: [fa[b][i] + (fb[b][i] - fa[b][i]) * t for i in range(3)] + nlerp(fa[b][3:], fb[b][3:], t) for b in bones}

seq, fps, names = [], None, []
for spec in specs:
    aid, _, loops = spec.partition(':')
    a = by_id[aid]; fps = fps or a['fps']
    fr = a['frames'][:-1] if len(a['frames']) > 1 else a['frames']   # last frame = first frame of the next loop
    clip = fr * int(loops or 2)
    names.append(f"{aid} (layer {a['layer']} state {a['state']}, {a['length']:.2f} s x{int(loops or 2)})")
    if seq and BLEND > 0:
        nb = max(1, int(BLEND * fps))
        for i in range(min(nb, len(clip))):
            clip[i] = mix(seq[-1], clip[i], (i + 1) / (nb + 1))
    seq += clip
seq += [seq[-1]] * int(HOLD * fps)

# world motion from the planted foot
off, prev_foot, prev = [0.0, 0.0], None, None
frames = []
for f in seq:
    foot = 'l_foot' if f['l_foot'][2] <= f['r_foot'][2] else 'r_foot'
    if prev_foot == foot and prev is not None and f[foot][2] < 0.16:
        off[0] -= (f[foot][0] - prev[foot][0]) * SPEED; off[1] -= (f[foot][1] - prev[foot][1]) * SPEED
    prev, prev_foot = f, foot
    frames.append({b: [f[b][0] + off[0], f[b][1] + off[1]] + f[b][2:] for b in bones})

def lua(v):
    if isinstance(v, dict): return '{' + ','.join(f'[{json.dumps(k)}]={lua(x)}' for k, x in v.items()) + '}'
    if isinstance(v, list): return '{' + ','.join(lua(x) for x in v) + '}'
    if isinstance(v, str): return json.dumps(v)
    return repr(round(v, 5)) if isinstance(v, float) else repr(v)
with open(out, 'w') as f:
    f.write('-- generated by sim/prepare.py from ' + src + '\n-- ' + '; '.join(names) + '\nreturn ')
    f.write(lua({'fps': fps, 'bones': bones, 'rest': D['rest'], 'clips': names, 'frames': frames}))
if out.endswith('.lua'):   # the same frames as JSON too, for the Blender renderer (sim/render_armor.py)
    json.dump({'fps': fps, 'bones': bones, 'rest': D['rest'], 'frames': frames}, open(out[:-4] + '.json', 'w'))
print(f'prepare: {len(frames)} frames at {fps} fps ({len(frames) / fps:.1f} s), travelled {math.hypot(*off):.2f} m -> {out}')
