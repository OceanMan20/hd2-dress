"""Step 3 stress sequence: the game's most extreme Helldiver moves back to back, for sim/stress.lua.
   python3 sim/stress_prepare.py ALL_ANIMS.json OUT.lua
ALL_ANIMS.json comes from sim/anim_export.py (every animation, with the arm/torso joints). The moves
were picked by motion (hips height, travel, speed), see docs/PROJECT_LOG.md step 3:
stand, dive, lie prone, crawl x2, get up, stand, a violent hit reaction (hips 9 m/s, hands 17 m/s),
a knock-down and getting back up (hips 10 m/s), stand. Each move continues where the last one ended
(hips over the ground), and the cut between moves is a snap, harsher than the game's blending.
Resampled to 60 fps (the solvers substep at 60 Hz either way)."""
import json, math, sys
SRC, OUT = sys.argv[1], sys.argv[2]
SEQ = [('stand', '15973994310853105570', 'first', 0.5), ('dive', '15973994310853105570', 'play', 0),
       ('prone', '15973994310853105570', 'last', 0.6), ('crawl', '962193287716325945', 'play', 0),
       ('crawl', '962193287716325945', 'play', 0), ('get up', '2463154135084150628', 'play', 0),
       ('stand', '2463154135084150628', 'last', 0.5), ('hit', '2635010984077288310', 'play', 0),
       ('knock-down', '14215076477113324800', 'play', 0), ('stand', '14215076477113324800', 'last', 0.8)]
JOINTS = ['hips', 'spine1', 'chest', 'neck', 'head', 'l_shoulder', 'l_elbow', 'l_hand', 'r_shoulder', 'r_elbow', 'r_hand',
          'l_thigh', 'l_knee', 'l_foot', 'l_toe', 'r_thigh', 'r_knee', 'r_foot', 'r_toe']
d = json.load(open(SRC))
anims = {a['id']: a for a in d['anims']}

def lerp(a, b, t): return [a[i] + (b[i] - a[i]) * t for i in range(len(a))]
def nlerp(a, b, t):
    if sum(x * y for x, y in zip(a, b)) < 0: b = [-x for x in b]
    q = lerp(a, b, t); n = math.sqrt(sum(x * x for x in q)) or 1
    return [x / n for x in q]
def sample(a, t):
    F = a['frames']; x = t * a['fps']; i = min(len(F) - 2, int(x)); f = x - i
    out = {}
    for j in JOINTS:
        p0, p1 = F[i][j], F[i + 1][j]
        out[j] = lerp(p0[:3], p1[:3], f) + nlerp(p0[3:], p1[3:], f)
    return out

frames, marks, shift = [], [], [0.0, 0.0]
for name, aid, how, dur in SEQ:
    a = anims[aid]
    if how == 'play': ts = [k / 60 for k in range(int(a['length'] * 60))]
    else: ts = [0.0 if how == 'first' else a['length'] - 1e-6] * int(dur * 60)
    first = sample(a, ts[0])
    if frames:   # continue over the ground where the last move ended
        shift = [frames[-1]['hips'][0] - first['hips'][0] + shift[0] * 0, frames[-1]['hips'][1] - first['hips'][1]]
    marks.append((len(frames) + 1, name))
    for t in ts:
        s = sample(a, t)
        for j in JOINTS: s[j][0] += shift[0]; s[j][1] += shift[1]
        frames.append(s)

with open(OUT, 'w') as f:
    f.write('-- generated by sim/stress_prepare.py: %d frames at 60 fps\nreturn {\n' % len(frames))
    f.write(' rest = {' + ', '.join('%s = {%s}' % (j, ','.join('%.5g' % v for v in d['rest'][j])) for j in JOINTS) + '},\n')
    f.write(' marks = {' + ', '.join('{%d, "%s"}' % m for m in marks) + '},\n frames = {\n')
    for s in frames:
        f.write('  {' + ', '.join('%s = {%s}' % (j, ','.join('%.5g' % v for v in s[j])) for j in JOINTS) + '},\n')
    f.write(' },\n}\n')
print('stress sequence: %d frames (%.1f s): %s' % (len(frames), len(frames) / 60, ', '.join(m[1] for m in marks)))
